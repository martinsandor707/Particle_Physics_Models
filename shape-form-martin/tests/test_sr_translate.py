def test_sign_folds_into_literals_only():
    e = T.parse("x * -1.5")
    assert T.to_dict(e) == {"k": "op", "n": "*", "a": [{"k": "var", "n": "x"}, {"k": "const", "v": -1.5}]}
    assert T.n_constants(T.parse("zt + -0.25")) == 1 and T.n_constants(T.parse("zt - -0.25")) == 1
    e = T.parse("-x")
    assert e.kind == "op" and e.name == "neg"
    e = T.parse("-x^2")                                    # -(x^2), as in Julia and Python
    assert e.name == "neg" and e.args[0].name == "square"
    assert T.evaluate(T.parse("-2^2")) == -4.0 and T.evaluate(T.parse("(-2)^2")) == 4.0
    assert T.evaluate(T.parse("2^-2")) == 0.25 and T.evaluate(T.parse("2 ^ 3 ^ 2")) == 512.0   # right-associative
    assert T.evaluate(T.parse("1 - 2 - 3")) == -4.0 and T.evaluate(T.parse("8 / 4 / 2")) == 1.0
    assert T.evaluate(T.parse("1 + 2 * 3")) == 7.0 and T.evaluate(T.parse("+3")) == 3.0


def test_powers():
    assert T.parse("u^2") == T.op("square", T.var("u")) == T.parse("u**2") == T.parse("pow(u, 2)")
    e = T.parse("u^3")
    assert e.name == "pow" and e.args[1].fixed and e.args[1].value == 3.0 and T.n_constants(e) == 0
    e = T.parse("u^-2")
    assert e.args[1].fixed and e.args[1].value == -2.0
    e = T.parse("u^2.5")
    assert e.name == "pow" and not e.args[1].fixed and T.n_constants(e) == 1
    e = T.parse("u^v")
    assert e.name == "pow" and e.args[1].kind == "var"
    u = np.array([-2.0, -0.5, 0.5, 3.0])
    assert np.allclose(T.evaluate(T.parse("u^3"), u=u), u ** 3) and np.allclose(T.evaluate(T.parse("u^-2"), u=u), u ** -2.0)
    with np.errstate(all="ignore"):
        v = T.evaluate(T.parse("u^2.5"), u=u)
    assert np.isnan(v[0]) and np.isnan(v[1]) and np.allclose(v[2:], u[2:] ** 2.5)     # real power: no guard


