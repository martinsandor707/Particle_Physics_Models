def test_constants_order_and_torch_parameters():
    e = T.parse("tanh((zt * 1.3) + -0.4) * 0.5 + ppow(rh, 0.25) * (x ^ 3)")
    assert T.constants(e) == [1.3, -0.4, 0.5, 0.25] and T.n_constants(e) == 4
    m = T.TorchExpr(e)
    assert m.c.dtype == torch.float64 and m.c.tolist() == [1.3, -0.4, 0.5, 0.25] and m.n_params() == 4
    assert [n for n, _ in m.named_parameters()] == ["c"]
    zt, rh, x = (torch.tensor(v, dtype=torch.float64) for v in ([0.3, 1.0], [2.0, 5.0], [-0.5, 0.7]))
    out = m(zt, rh, x)
    out.sum().backward()
    assert m.c.grad is not None and torch.all(torch.isfinite(m.c.grad)) and torch.all(m.c.grad != 0)
    with torch.no_grad():
        m.c.copy_(torch.tensor([1.0, 0.0, 2.0, 0.5]))
    e2 = m.current_expr()
    assert T.constants(e2) == [1.0, 0.0, 2.0, 0.5] and T.to_dict(e2) == T.to_dict(T.with_constants(e, [1, 0, 2, 0.5]))
    assert np.allclose(m(zt, rh, x).detach().numpy(),
                       T.evaluate(e2, zt=zt.numpy(), rh=rh.numpy(), x=x.numpy()), rtol=1e-14)
    assert np.allclose(m({"zt": zt, "rh": rh, "x": x}).detach().numpy(), m(zt, rh, x).detach().numpy())
    with pytest.raises(ValueError):
        T.with_constants(e, [1.0])
    frozen = T.TorchExpr(e, trainable=False)
    assert not frozen.c.requires_grad


