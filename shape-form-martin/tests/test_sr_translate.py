def test_template_translation():
    t, parts = T.parse_template("s1_tanh_sum", {"u": "#1 * 0.6", "v": "0.3 - #2", "w": "square(#1 * #2)"},
                                keep_parts=True)
    assert T.to_string(t) == "tanh(((zt * 0.6) + (0.3 - x)) + square(zt * rh))"
    assert set(parts) == {"u", "v", "w"} and T.n_constants(t) == 2
    t2 = T.parse_template_string("s1_tanh_sum", "u = #1 * 0.6; v = 0.3 - #2; w = square(#1 * #2)")
    assert t2 == t
    t = T.parse_template("s2_modulation", {"f": "tanh(#1)", "a": "1.64", "e": "#1 + (#2 * 0.196)", "ph": "1.64 * #3"})
    fixed = [n.value for n in T.walk(t) if n.kind == "const" and n.fixed]
    assert sorted(fixed) == [0.3, 1.0, 1.0]                # the template's own literals: not trained, not in k
    assert T.constants(t) == [1.64, 0.196, 1.64] and T.n_constants(t) == 3
    m = T.TorchExpr(t)
    assert m.c.numel() == 3
    zt, rh, x = 0.7, 2.0, -0.3
    want = math.tanh(math.tanh(zt)) + 0.3 * math.tanh(1.64) / (1 + (zt + rh * 0.196) ** 2) * math.sin(1.64 * x)
    assert T.evaluate(t, zt=zt, rh=rh, x=x) == pytest.approx(want, rel=1e-14)
    assert T.from_dict(T.to_dict(t)) == t                  # the lossless form keeps the fixed marks
    assert [n.fixed for n in T.walk(T.parse(T.to_string(t))) if n.kind == "const"].count(True) == 0   # the string not


