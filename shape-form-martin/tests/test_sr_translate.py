def _fixture_rows():
    for key, run in FIXTURE["runs"].items():
        for i, row in enumerate(run["rows"]):
            yield pytest.param(key, i, id=f"{key}[{row['c']}]")


@pytest.mark.parametrize("key,i", list(_fixture_rows()))
def test_translation_equals_pysr_prediction_and_loss(key, i):
    run = FIXTURE["runs"][key]
    row = run["rows"][i]
    X, y, w = (np.array(FIXTURE[k]) for k in ("X", "y", "w"))
    if run["template"] is None:
        e = T.parse(row["eq"], VN)
        assert T.complexity(e) == row["c"]                 # the search's complexity = tree_complexity
    else:
        e, parts = T.parse_template_string(run["template"], row["eq"], keep_parts=True)
        assert sum(T.complexity(p) for p in parts.values()) == row["c"]   # template: the sum over sub-expressions
        assert T.n_constants(e) == sum(T.n_constants(p) for p in parts.values())
    pred = np.array(row["pred"])
    rt = T.round_trip(e, X, VN, reference=pred)
    assert rt["passed"], rt
    assert rt["reference_max_diff"] <= 1e-12 and rt["numpy_torch_max_diff"] <= 1e-12   # far inside the 1e-5 rule
    v = T.evaluate(e, {n: X[:, j] for j, n in enumerate(VN)}) + np.zeros(len(X))
    loss = O.wl2_loss_numpy(v, y, w) if run["loss"] == "wl2" else O.gauge_loss_numpy(v, y, w, X[:, 2])
    assert loss == pytest.approx(row["loss"], rel=1e-9, abs=1e-15)
