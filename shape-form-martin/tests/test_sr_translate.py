@pytest.mark.parametrize("name", sorted(O.OPS))
def test_every_operator_numpy_torch(name):
    spec = O.OPS[name]
    rng = np.random.default_rng(sorted(O.OPS).index(name))
    positive = ("log", "log1p", "sqrt", "pow", "inv", "/")
    a = rng.uniform(0.05, 3.0, 200) if name in positive else rng.uniform(-3.0, 3.0, 200)
    b = rng.uniform(-2.0, 2.0, 200) + (3.0 if name == "/" else 0.0)
    if spec.arity == 1:
        s = f"{name}(u)"
    elif name in ("+", "-", "*", "/"):
        s = f"u {name} v"
    elif name == "pow":
        s = "u ^ v"
    else:
        s = f"{name}(u, v)"
    e = T.parse(s)
    assert e.kind == "op" and e.name == name
    ref = O.numpy_impl(name)(a) if spec.arity == 1 else O.numpy_impl(name)(a, b)
    v_np = T.evaluate(e, u=a, v=b)
    assert np.array_equal(v_np, ref)
    m = T.TorchExpr(e, ("u", "v"))
    with torch.inference_mode():
        v_t = m(torch.tensor(a), torch.tensor(b)).numpy()
        v_32 = T.TorchExpr(e, ("u", "v"), dtype=torch.float32)(torch.tensor(a), torch.tensor(b)).double().numpy()
    assert np.max(np.abs(v_t - ref) / np.maximum(1.0, np.abs(ref))) <= 1e-13
    assert np.max(np.abs(v_32 - ref) / np.maximum(1.0, np.abs(ref))) <= T.ROUND_TRIP_TOL
    rt = T.round_trip(T.parse(T.to_string(e)), np.column_stack([a, b]), ("u", "v"))
    assert rt["passed"] and rt["numpy_torch_max_diff"] <= 1e-12


