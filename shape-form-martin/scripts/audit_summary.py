"""M1 audit - write results/m1_audit/SUMMARY.md from the JSON files of the audit scripts (no GPU, no data).

    uv run python -B shape-form-martin/scripts/audit_summary.py

Order of the audit runs (each re-runnable, each writes its own JSON):
    audit_parts.py (sanity + shared parts) -> audit_d1.py, audit_d2.py, audit_d3.py, audit_d4.py, audit_d5.py,
    audit_d6a.py, audit_d6d.py, audit_d8.py, audit_d9.py -> audit_summary.py
"""
import json
import subprocess
import sys
from pathlib import Path

sys.dont_write_bytecode = True
MARTIN = Path(__file__).resolve().parents[1]
OUT = MARTIN / "results" / "m1_audit"
NAMES = ("sanity", "d1", "d2", "d3", "d4", "d5", "d6a", "d6d", "d8", "d9")


def J(name):
    return json.loads((OUT / f"{name}.json").read_text())


def ms(x, scale=1.0, nd=3, sign=True):
    """mean ± se in units of 1/scale."""
    if x is None or x.get("mean") is None:
        return "–"
    se = x.get("se")
    m = f"{x['mean'] * scale:+.{nd}f}" if sign else f"{x['mean'] * scale:.{nd}f}"
    return f"{m} ± {se * scale:.{nd}f}" if se is not None else m


def f(x, nd=4, sign=False):
    if x is None:
        return "–"
    return f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def matrix(M, zl, rl, fmt):
    rows = [[zl[i]] + [fmt(M[i][j]) for j in range(len(rl))] for i in range(len(zl))]
    return table(["z' \\ r [mm]"] + rl, rows)


def git_head():
    try:
        return subprocess.run(["git", "-C", str(MARTIN), "rev-parse", "--short", "HEAD"], capture_output=True,
                              text=True, check=True).stdout.strip()
    except Exception:
        return "?"


