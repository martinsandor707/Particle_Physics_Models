    rows = [[gname, v["n_events"], ms(v["gap"], 1e4, 2), ms(v["hit_term"], 1e4, 2), ms(v["norm_term"], 1e4, 2),
             f"{v['closure_hit_plus_norm_minus_gap']:.1e}"] for gname, v in d2["groups"].items()]
