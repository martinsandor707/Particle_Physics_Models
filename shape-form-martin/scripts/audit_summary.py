    w(table(hdr5, d5rows(d5["zb_strata"])) + "\n")
    rows = [[lab, ms(r["formula_minus_mlp"]["front"], 1e3, 3), ms(r["formula_minus_mlp"]["beyond_zb"], 1e3, 3)]
            for lab, r in ({"all": d5["all"]} | d5["theta_quintile"] | d5["zb_strata"]).items()]
    w(table(["stratum", "front: formula − MLP [10⁻³]", "beyond zb: formula − MLP [10⁻³]"], rows) + "\n")
