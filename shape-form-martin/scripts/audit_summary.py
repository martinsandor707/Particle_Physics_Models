    w(matrix(ga["coarse_signed"], zl, rl, lambda x: f"{x * 1e4:+.2f}") + "\n")
    w("**All events — SE of the signed regional hit term [10⁻⁴ nat/event]**\n")
    w(matrix(ga["coarse_signed_se"], zl, rl, lambda x: f"{x * 1e4:.2f}") + "\n")
    w("**All events — absolute contribution |signed regional total| [10⁻⁴]** is the modulus of the first matrix; "
      "for scale, the event-mean of Σ_i |w_i ln g^MLP − w_i ln g^F| per region [10⁻⁴]:\n")
    w(matrix(ga["coarse_sum_abs_per_hit_terms"], zl, rl, lambda x: f"{x * 1e4:.2f}") + "\n")
    for gname, v in d2["groups"].items():
        if gname == "all":
            continue
        w(f"**p {gname} GeV (n = {v['n_events']}) — signed regional hit term [10⁻⁴]; norm term "
          f"{ms(v['norm_term'], 1e4, 2)}**\n")
        w(matrix(v["coarse_signed"], zl, rl, lambda x: f"{x * 1e4:+.1f}") + "\n")
    w("**Gap budget** (regions ranked by signed contribution, largest first, until 50 % / 80 % of the signed hit-term "
      "total is reached; and by |contribution| until 50 % / 80 % of Σ|contribution|). Values in 10⁻⁴ nat.\n")
    rows = []
    for gname, v in d2["groups"].items():
        b = v["budget"]
        rows.append([gname, f"{b['signed_total'] * 1e4:+.2f}", b["signed_50pct"]["n_regions"],
                     b["signed_80pct"]["n_regions"], f"{b['abs_total'] * 1e4:.2f}", b["abs_50pct"]["n_regions"],
                     b["abs_80pct"]["n_regions"]])
    w(table(["group", "signed total", "# regions 50 % signed", "# 80 % signed", "Σ|c|", "# 50 % abs", "# 80 % abs"],
            rows) + "\n")
    for gname, v in d2["groups"].items():
        b = v["budget"]
        sg = "; ".join(f"{x['region']} {x['value'] * 1e4:+.2f}" for x in b["signed_80pct"]["regions"])
