    def ev_rows(evs):
        return [[e["event_number"], f"{e['p_GeV']:.4f}", f"{e['theta_rad']:.3f}", e["n_hits"], f"{e['evis']:.2e}",
                 f"{e['deepest_hit_z_mm']:.0f}", f"{e['largest_hit_r_mm']:.0f}", f"{e['ew_mean_z_mm']:.0f}",
                 f"{e['ew_mean_r_mm']:.0f}", f"{e['nll_mlp']:.3f}", f"{e['nll_formula']:.3f}", f"{e['d_e']:+.4f}",
                 f"{e['gap_change_if_left_out']:+.2e}"] for e in evs]
    w(table(hdr, ev_rows(lv["events"])) + "\n")
    lt = d1["low_p_train"]
    w(f"**Training events with p < 0.1 GeV** ({lt['n']}; training gap {ms(lt['train_gap'], 1, 6)}; training "
      f"medians {lt['hits_median_all_train']:.0f} hits, evis {lt['evis_median_all_train']:.4f}). Δgap refers to the "
      "training gap.\n")
